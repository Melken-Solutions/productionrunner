-- ProductionRunner private application schema. Never expose through the Data API.

SET search_path TO productionrunner, pg_catalog;
CREATE COLLATION pr_nocase (provider=icu,locale='und-u-ks-level2',deterministic=false);

CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS tenants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS memberships (
 tenant_id BIGINT NOT NULL REFERENCES tenants(id), user_id BIGINT NOT NULL REFERENCES users(id),
 roles TEXT NOT NULL, PRIMARY KEY(tenant_id, user_id)
);

CREATE TABLE IF NOT EXISTS tickets (
 id TEXT PRIMARY KEY, tenant_id BIGINT NOT NULL REFERENCES tenants(id), pn TEXT NOT NULL, revision TEXT NOT NULL,
 quantity BIGINT NOT NULL CHECK(quantity > 0), tracking TEXT NOT NULL CHECK(tracking IN ('batch','serial')),
 serials TEXT NOT NULL, instructions TEXT NOT NULL,
 state TEXT NOT NULL CHECK(state IN ('ready','in_progress','awaiting_inspection','accepted','held')),
 created_by BIGINT NOT NULL REFERENCES users(id), created_at TEXT NOT NULL,
 version BIGINT NOT NULL DEFAULT 1,
 UNIQUE(tenant_id, id),
 FOREIGN KEY(tenant_id, created_by) REFERENCES memberships(tenant_id, user_id)
);

CREATE TABLE IF NOT EXISTS operations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id BIGINT NOT NULL, ticket_id TEXT NOT NULL REFERENCES tickets(id),
 sequence BIGINT NOT NULL, name TEXT NOT NULL, instructions TEXT NOT NULL,
 completed_by BIGINT REFERENCES users(id), completed_at TEXT,
 UNIQUE(ticket_id, sequence),
 FOREIGN KEY(tenant_id, ticket_id) REFERENCES tickets(tenant_id, id),
 FOREIGN KEY(tenant_id, completed_by) REFERENCES memberships(tenant_id, user_id)
);

CREATE TABLE IF NOT EXISTS inspections (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id BIGINT NOT NULL, ticket_id TEXT NOT NULL UNIQUE REFERENCES tickets(id),
 inspector_id BIGINT NOT NULL REFERENCES users(id), result TEXT NOT NULL CHECK(result IN ('pass','fail')),
 notes TEXT NOT NULL, created_at TEXT NOT NULL,
 FOREIGN KEY(tenant_id, ticket_id) REFERENCES tickets(tenant_id, id),
 FOREIGN KEY(tenant_id, inspector_id) REFERENCES memberships(tenant_id, user_id)
);

CREATE TABLE IF NOT EXISTS events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id BIGINT NOT NULL, ticket_id TEXT NOT NULL REFERENCES tickets(id),
 actor_id BIGINT NOT NULL REFERENCES users(id), action TEXT NOT NULL, detail TEXT NOT NULL, created_at TEXT NOT NULL,
 FOREIGN KEY(tenant_id, ticket_id) REFERENCES tickets(tenant_id, id),
 FOREIGN KEY(tenant_id, actor_id) REFERENCES memberships(tenant_id, user_id)
);

CREATE FUNCTION events_no_update_fn() RETURNS trigger LANGUAGE plpgsql SET search_path TO productionrunner, pg_catalog AS $$ BEGIN RAISE EXCEPTION 'Audit events are immutable' USING ERRCODE='23514'; RETURN NEW; END $$;

CREATE TRIGGER events_no_update BEFORE UPDATE ON events FOR EACH ROW EXECUTE FUNCTION events_no_update_fn();

CREATE FUNCTION events_no_delete_fn() RETURNS trigger LANGUAGE plpgsql SET search_path TO productionrunner, pg_catalog AS $$ BEGIN RAISE EXCEPTION 'Audit events are immutable' USING ERRCODE='23514'; RETURN OLD; END $$;

CREATE TRIGGER events_no_delete BEFORE DELETE ON events FOR EACH ROW EXECUTE FUNCTION events_no_delete_fn();

